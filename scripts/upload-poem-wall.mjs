// Upload the poem-instagram archive to Cloudinary (HEIC ingested natively,
// delivered as WebP via f_auto by CldImage), clustered into multi-page poems.
// Emits lib/poem-wall-data.ts — the manifest the /poetry/wall room consumes.
//
//   node scripts/upload-poem-wall.mjs
//
// Skips .webp (those are studio photos, not poems). Idempotent (overwrite:true).

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { v2 as cloudinary } from 'cloudinary';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SRC = join(ROOT, 'public', 'assets', 'poem-instagram');
const BASE = 'creativelynanda';
const FOLDER = 'poem-wall';

for (const line of readFileSync(join(ROOT, '.env.local'), 'utf8').split('\n')) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].trim().replace(/^["']|["']$/g, '');
}
cloudinary.config({
  cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
  api_key: process.env.CLOUDINARY_API_KEY,
  api_secret: process.env.CLOUDINARY_API_SECRET,
  secure: true,
});

// ── cluster the source files into poems ──────────────────────────────────────
const files = readdirSync(SRC).filter((f) => /\.(jpe?g|png)$/i.test(f)); // .jpg/.jpeg/.png (skip .webp studio photos)
const clusters = {};
let artIdx = 0;
const artOrder = files.filter((f) => /^photo-output/i.test(f)).sort();
for (const f of files) {
  let m = f.match(/^IMG_(\d{8})_(\d{6})_(\d+)\./i);
  if (m) {
    const id = `c-${m[1]}-${m[2]}`;
    (clusters[id] ||= { id, kind: 'carousel', pages: [] }).pages.push({ src: f, sort: parseInt(m[3], 10) });
    continue;
  }
  if (/^photo-output/i.test(f)) {
    const id = `art-${String(artOrder.indexOf(f) + 1).padStart(2, '0')}`;
    (clusters[id] ||= { id, kind: 'art', pages: [] }).pages.push({ src: f, sort: 0 });
    continue;
  }
  const id = `x-${f.replace(/\.[^.]+$/, '').toLowerCase().replace(/[^a-z0-9]+/g, '-')}`;
  (clusters[id] ||= { id, kind: 'single', pages: [] }).pages.push({ src: f, sort: 0 });
}

// order poems: art cards first, then carousels by page-count desc, then singles
const poems = Object.values(clusters);
poems.forEach((p) => p.pages.sort((a, b) => a.sort - b.sort));
poems.sort((a, b) => {
  const rank = (k) => (k === 'art' ? 0 : k === 'carousel' ? 1 : 2);
  if (rank(a.kind) !== rank(b.kind)) return rank(a.kind) - rank(b.kind);
  return b.pages.length - a.pages.length;
});

console.log(`Uploading ${files.length} files across ${poems.length} poems …`);
let ok = 0, fail = 0;
const manifest = [];
for (const poem of poems) {
  const pageIds = [];
  for (let i = 0; i < poem.pages.length; i++) {
    const abs = join(SRC, poem.pages[i].src);
    const publicId = `${BASE}/${FOLDER}/${poem.id}-p${String(i + 1).padStart(2, '0')}`;
    try {
      const r = await cloudinary.uploader.upload(abs, {
        public_id: publicId, resource_type: 'image', overwrite: true, invalidate: true,
        use_filename: false, unique_filename: false,
      });
      pageIds.push(publicId);
      ok++;
      process.stdout.write(`  ok ${poem.id}-p${i + 1} [${r.width}x${r.height}]\n`);
    } catch (e) { fail++; console.log(`  FAIL ${publicId}: ${e.message}`); }
  }
  if (pageIds.length) manifest.push({ id: poem.id, kind: poem.kind, pages: pageIds });
}

// ── emit the TS manifest ─────────────────────────────────────────────────────
const ts = `// AUTO-GENERATED by scripts/upload-poem-wall.mjs — do not edit by hand.
// The poem archive from @nanda.regine, clustered into poems (Instagram carousels
// = one multi-page poem). Cloudinary public_ids; CldImage delivers WebP.

export type WallPoemKind = 'art' | 'carousel' | 'single';

export interface WallPoem {
  id: string;
  kind: WallPoemKind;
  pages: string[]; // Cloudinary public_ids, in reading order
}

export const POEM_WALL: WallPoem[] = ${JSON.stringify(manifest, null, 2)};

export const POEM_WALL_COUNT = ${manifest.length};
`;
writeFileSync(join(ROOT, 'lib', 'poem-wall-data.ts'), ts);
console.log(`\nDone. ${ok} uploaded, ${fail} failed. ${manifest.length} poems -> lib/poem-wall-data.ts`);
