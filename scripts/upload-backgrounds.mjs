// Upload the curated background-texture library to Cloudinary under
// creativelynanda/backgrounds/<sanitized-name>. Filenames have spaces/parens,
// so we sanitize to kebab-case ids. Emits lib/backgrounds-data.ts (the list of
// available textures) for the magazine-depth <TexturedSection> system.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, extname } from 'node:path';
import { v2 as cloudinary } from 'cloudinary';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SRC = join(ROOT, 'public', 'assets', 'background images');
const BASE = 'creativelynanda';
const FOLDER = 'backgrounds';

for (const line of readFileSync(join(ROOT, '.env.local'), 'utf8').split('\n')) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].trim().replace(/^["']|["']$/g, '');
}
cloudinary.config({
  cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
  api_key: process.env.CLOUDINARY_API_KEY,
  api_secret: process.env.CLOUDINARY_API_SECRET,
  secure: true,
});

// retire pile from the catalog (generic filler / dupes / low-res) — skip these
const RETIRE = [
  'abstract colorful design', '50 pink aesthetic', 'trendy abstract', 'download (16)',
  'download (21)', 'download (44)', 'download (25)', 'download (31)',
];
const sanitize = (f) => f.replace(extname(f), '')
  .toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '')
  .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60) || 'bg';

const files = readdirSync(SRC).filter((f) => /\.(jpe?g|png)$/i.test(f));
const uploaded = [];
let ok = 0, fail = 0, skipped = 0;
const usedIds = new Set();
for (const f of files) {
  const low = f.toLowerCase();
  if (RETIRE.some((r) => low.includes(r))) { skipped++; continue; }
  let id = sanitize(f);
  while (usedIds.has(id)) id = id + '-2';
  usedIds.add(id);
  const publicId = `${BASE}/${FOLDER}/${id}`;
  try {
    const r = await cloudinary.uploader.upload(join(SRC, f), {
      public_id: publicId, resource_type: 'image', overwrite: true, invalidate: true,
      use_filename: false, unique_filename: false,
    });
    uploaded.push({ id: publicId, w: r.width, h: r.height, from: f });
    ok++;
    process.stdout.write(`  ok ${id} [${r.width}x${r.height}]\n`);
  } catch (e) { fail++; console.log(`  FAIL ${f}: ${e.message}`); }
}

const ts = `// AUTO-GENERATED by scripts/upload-backgrounds.mjs — do not edit by hand.
// Curated background textures (soul palette: warm-rose, gold, regal-navy) for the
// magazine-depth <TexturedSection>. Cloudinary public_ids; served via cldImg().

export const BACKGROUNDS: string[] = ${JSON.stringify(uploaded.map((u) => u.id), null, 2)};
`;
writeFileSync(join(ROOT, 'lib', 'backgrounds-data.ts'), ts);
console.log(`\nDone. ${ok} uploaded, ${fail} failed, ${skipped} skipped (retire pile). -> lib/backgrounds-data.ts`);
